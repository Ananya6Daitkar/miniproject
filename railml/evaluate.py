"""Held-out evaluation, paired scenarios, per-training-seed reporting."""
import argparse
import csv
from dataclasses import replace
import hashlib
import json
from pathlib import Path
import shutil

import numpy as np
import torch

from .baselines import run_episode
from .environment import Config
from .sac import SAC

TEST_SEEDS = list(range(200000, 200020))
POLICIES = ["sac", "cp_sat", "threshold", "no_maintenance"]


def stats(values):
    return {"mean": float(np.mean(values)),
            "std": float(np.std(values, ddof=1)) if len(values) > 1 else 0.,
            "n": len(values)}


def evaluate(directory="artifacts"):
    root = Path(directory)
    manifests = [json.loads(p.read_text()) for p in sorted(root.glob("seed_*/manifest.json"))]
    if not manifests:
        raise RuntimeError("Train at least one model before evaluating")
    # Choose demo checkpoint ONLY using validation; test scores cannot select it.
    selected = max(manifests, key=lambda x: x["best_validation_return"])
    shutil.copyfile(root / f"seed_{selected['seed']}/best.pt", root / "demo.pt")
    rows, traces = [], {}
    torch.set_num_threads(1)
    for name, config in (
        ("standard", Config()),
        ("stress", replace(Config(), deterioration_multiplier=1.5, closure_probability=.30)),
    ):
        for manifest in manifests:
            training_seed = manifest["seed"]
            model = SAC.load(root / f"seed_{training_seed}/best.pt")
            for test_seed in TEST_SEEDS:
                result = run_episode(config, test_seed, "sac", model)
                rows.append({"suite": name, "policy": "sac", "training_seed": training_seed,
                             "scenario_seed": test_seed, **result["metrics"]})
        for policy in POLICIES[1:]:
            for test_seed in TEST_SEEDS:
                result = run_episode(config, test_seed, policy)
                rows.append({"suite": name, "policy": policy, "training_seed": -1,
                             "scenario_seed": test_seed, **result["metrics"]})
        print(f"Evaluated {name}: {len(TEST_SEEDS)} held-out scenarios per policy/run", flush=True)
    metric_keys = list(rows[0].keys())[4:]
    summary = {}
    for suite in ("standard", "stress"):
        summary[suite] = {}
        for policy in POLICIES:
            group = [r for r in rows if r["suite"] == suite and r["policy"] == policy]
            summary[suite][policy] = {k: stats([r[k] for r in group]) for k in metric_keys}
    per_seed = {
        str(m["seed"]): {
            suite: stats([r["return"] for r in rows
                          if r["policy"] == "sac" and r["training_seed"] == m["seed"]
                          and r["suite"] == suite])
            for suite in ("standard", "stress")}
        for m in manifests}
    paired = {}
    for suite in ("standard", "stress"):
        paired[suite] = {}
        for baseline in POLICIES[1:]:
            differences = []
            for scenario in TEST_SEEDS:
                sac = np.mean([r["return"] for r in rows if r["suite"] == suite
                               and r["scenario_seed"] == scenario and r["policy"] == "sac"])
                base = next(r["return"] for r in rows if r["suite"] == suite
                            and r["scenario_seed"] == scenario and r["policy"] == baseline)
                differences.append(sac - base)
            paired[suite][baseline] = stats(differences)
    report = {"test_seeds": TEST_SEEDS, "training_runs": manifests,
              "selected_demo_seed": selected["seed"], "summary": summary,
              "per_training_seed_returns": per_seed, "paired_return_advantage": paired,
              "statistics_note": "SAC summary pools runs × scenarios; std is descriptive, not a "
              "confidence interval. Paired differences first average SAC runs per scenario.",
              "data": "Synthetic; no real railway inspection data",
              "checkpoint_sha256": hashlib.sha256((root / "demo.pt").read_bytes()).hexdigest()}
    (root / "evaluation.json").write_text(json.dumps(report, indent=2))
    with (root / "evaluation.csv").open("w") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    model = SAC.load(root / "demo.pt")
    for policy in POLICIES:
        traces[policy] = run_episode(Config(), TEST_SEEDS[0], policy, model)
    (root / "demo.json").write_text(json.dumps(traces))
    lines = [
        "# Measured results", "",
        "Generated by `python -m railml.evaluate`. These are simulator measurements, "
        "not the paper's published results.", "",
        "| Suite | Policy | Return ↑ | Cost ↓ | Mean condition ↓ | Overdue segment-windows ↓ |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for suite, policies in summary.items():
        for policy, values in policies.items():
            cells = [f'{values[k]["mean"]:.2f} ± {values[k]["std"]:.2f}'
                     for k in ("return", "cost", "mean_condition", "overdue_segment_windows")]
            lines.append(f"| {suite} | {policy} | " + " | ".join(cells) + " |")
    lines += ["", report["statistics_note"], "",
              f"Demo checkpoint selected by validation: training seed {selected['seed']}.",
              "All methods receive identical exogenous noise for a scenario seed. "
              "A lower cost alone is not success: doing nothing has zero maintenance cost "
              "but allows deterioration. Return combines cost and condition penalties.",
              "", "See `evaluation.csv` for every run and `evaluation.json` for per-run "
              "returns, paired differences, seeds and checkpoint hash."]
    (root / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print(json.dumps(summary["standard"], indent=2), flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--artifacts", default="artifacts")
    evaluate(parser.parse_args().artifacts)
